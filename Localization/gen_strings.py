#!/usr/bin/env python3
"""Generates the Swift and C# string tables from Localization/strings.json.
Usage: gen_strings.py <repo-root>"""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1])
data = json.loads((root / "Localization/strings.json").read_text(encoding="utf-8"))
langs = [code for code, _ in data["languages"]]
keys = list(data["strings"])

for key, table in data["strings"].items():
    missing = [l for l in langs if l not in table]
    if missing:
        sys.exit(f"{key}: missing {missing}")


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


header = "Generated by Localization/gen_strings.py from Localization/strings.json; do not edit."

# Swift
sw = [f"// {header}", "import Foundation", "", "enum L10n {"]
sw.append("    /// (code, native name), in menu order.")
sw.append("    static let languages: [(String, String)] = [")
for code, name in data["languages"]:
    sw.append(f"        ({lit(code)}, {lit(name)}),")
sw.append("    ]")
sw.append(f"    static let rtl: Set<String> = [{', '.join(lit(c) for c in data['rtl'])}]")
sw.append("")
sw.append("    static let table: [String: [String: String]] = [")
for key in keys:
    sw.append(f"        {lit(key)}: [")
    for l in langs:
        sw.append(f"            {lit(l)}: {lit(data['strings'][key][l])},")
    sw.append("        ],")
sw.append("    ]")
sw.append("}")
(root / "Plowy/Sources/Plowy/L10nTable.swift").write_text("\n".join(sw) + "\n", encoding="utf-8")

# C#
cs = [f"// {header}", "namespace Plowy;", "", "public static partial class L10n", "{"]
cs.append("    /// (code, native name), in menu order.")
cs.append("    public static readonly (string Code, string Name)[] Languages =")
cs.append("    {")
for code, name in data["languages"]:
    cs.append(f"        ({lit(code)}, {lit(name)}),")
cs.append("    };")
cs.append(f"    public static readonly HashSet<string> Rtl = new() {{ {', '.join(lit(c) for c in data['rtl'])} }};")
cs.append("")
cs.append("    private static readonly Dictionary<string, Dictionary<string, string>> Table = new()")
cs.append("    {")
for key in keys:
    cs.append(f"        [{lit(key)}] = new()")
    cs.append("        {")
    for l in langs:
        cs.append(f"            [{lit(l)}] = {lit(data['strings'][key][l])},")
    cs.append("        },")
cs.append("    };")
cs.append("}")
(root / "PlowyWin/Core/L10nTable.cs").write_text("\n".join(cs) + "\n", encoding="utf-8")
print(f"{len(keys)} strings x {len(langs)} languages")
